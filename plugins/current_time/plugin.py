def _plural(n: int, one: str, few: str, many: str) -> str:
    n = abs(n) % 100

    if 10 < n < 20:
        return many

    last_digit = n % 10

    if last_digit == 1:
        return one

    if 2 <= last_digit <= 4:
        return few

    return many


def current_time():
    now = datetime.datetime.now()

    hours = now.hour
    minutes = now.minute

    hours_word = NUMBERS_TO_WORDS[hours][0]
    minutes_word = NUMBERS_TO_WORDS[minutes][1]

    hours_plural = _plural(hours, "час", "часа", "часов")
    minutes_plural = _plural(minutes, "минута", "минуты", "минут")

    phrases = [
        f"сейчас {hours_word} {hours_plural} {minutes_word} {minutes_plural}",
        f"сейчас {hours_word} {minutes_word}",
        f"{hours_word} {minutes_word}",
    ]

    if minutes == 0:
        phrases.insert(0, f"сейчас ровно {hours_word} {hours_plural}")

    vh.say_random(phrases)


