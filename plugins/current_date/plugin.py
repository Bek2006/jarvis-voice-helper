def _ordinal_genitive(n: int) -> str:
    """Возвращает порядковое числительное в родительном падеже."""
    if n in ORDINAL_GENITIVE:
        return ORDINAL_GENITIVE[n]


def _year_to_words_genitive(year: int) -> tuple:
    """
    Преобразует год в слова.
    Возвращает (текст_года, нужно_ли_добавлять_слово_года)
    """

    # 2000-2099
    if 2000 <= year <= 2099:
        rest = year - 2000
        if rest == 0:
            return "две тысячи", False
        return f"две тысячи {_ordinal_genitive(rest)}", True

    # 1900-1999
    if 1900 <= year <= 1999:
        rest = year - 1900
        if rest == 0:
            return "тысяча девятьсот", False
        return f"тысяча девятьсот {_ordinal_genitive(rest)}", True

    # 2100-2199
    if 2100 <= year <= 2199:
        rest = year - 2100
        if rest == 0:
            return "две тысячи сто", False
        return f"две тысячи сто {_ordinal_genitive(rest)}", True

    # 1800-1899
    if 1800 <= year <= 1899:
        rest = year - 1800
        if rest == 0:
            return "тысяча восемьсот", False
        return f"тысяча восемьсот {_ordinal_genitive(rest)}", True

    # 2200-2299
    if 2200 <= year <= 2299:
        rest = year - 2200
        if rest == 0:
            return "две тысячи двести", False
        return f"две тысячи двести {_ordinal_genitive(rest)}", True

    # 1700-1799
    if 1700 <= year <= 1799:
        rest = year - 1700
        if rest == 0:
            return "тысяча семьсот", False
        return f"тысяча семьсот {_ordinal_genitive(rest)}", True


def current_date():
    """Команда для озвучивания текущей даты."""
    today = datetime.date.today()

    day_word = DAY_ORDINALS[today.day]
    month_word = MONTHS_GENITIVE[today.month]
    year_word, need_year_word = _year_to_words_genitive(today.year)

    # Базовые фразы
    base_phrase = f"сегодня {day_word} {month_word}"

    phrases = [base_phrase]

    # Добавляем варианты с годом
    if need_year_word:
        # Для некруглых годов добавляем "года"
        phrases.append(f"{base_phrase} {year_word} года")
        phrases.append(f"{day_word} {month_word} {year_word} года")
    else:
        # Для круглых годов НЕ добавляем "года"
        phrases.append(f"{base_phrase} {year_word}")
        phrases.append(f"{day_word} {month_word} {year_word}")

    vh.say_random(phrases)


cmds = [current_date]

